CREATE DATABASE IF NOT EXISTS PREDICTIVEAI_FORGE;

CREATE SCHEMA IF NOT EXISTS PREDICTIVEAI_FORGE.INDUSTRIAL;

CREATE OR REPLACE TABLE PREDICTIVEAI_FORGE.INDUSTRIAL.TELEMETRY (
    MACHINE_ID VARCHAR,
    MACHINE_TYPE VARCHAR,
    HOUR NUMBER,
    TEMPERATURE_C FLOAT,
    VIBRATION_MM_S FLOAT,
    POWER_KW FLOAT,
    PRESSURE_BAR FLOAT,
    OPERATING_HOURS NUMBER,
    FAILURE NUMBER
);

CREATE OR REPLACE TABLE PREDICTIVEAI_FORGE.INDUSTRIAL.MACHINE_RISK (
    MACHINE_ID VARCHAR,
    MACHINE_TYPE VARCHAR,
    TEMPERATURE_C FLOAT,
    VIBRATION_MM_S FLOAT,
    POWER_KW FLOAT,
    PRESSURE_BAR FLOAT,
    FAILURE_RISK_PCT FLOAT,
    RISK_LEVEL VARCHAR
);

CREATE OR REPLACE TABLE PREDICTIVEAI_FORGE.INDUSTRIAL.MACHINE_DEPENDENCIES (
    SOURCE_MACHINE VARCHAR,
    TARGET_MACHINE VARCHAR,
    DEPENDENCY_TYPE VARCHAR,
    IMPACT_WEIGHT FLOAT
);

CREATE OR REPLACE TABLE PREDICTIVEAI_FORGE.INDUSTRIAL.FAILURE_CASCADE_RISK (
    SOURCE_MACHINE VARCHAR,
    TARGET_MACHINE VARCHAR,
    DEPENDENCY_TYPE VARCHAR,
    SOURCE_RISK FLOAT,
    IMPACT_WEIGHT FLOAT,
    PROPAGATED_RISK FLOAT,
    CASCADE_RISK_PCT FLOAT
);

CREATE OR REPLACE TABLE PREDICTIVEAI_FORGE.INDUSTRIAL.COUNTERFACTUAL_SIMULATIONS (
    MACHINE_ID VARCHAR,
    SCENARIO VARCHAR,
    CURRENT_RISK_PCT FLOAT,
    PROJECTED_RISK_PCT FLOAT,
    CASCADE_EXPOSURE_PCT FLOAT,
    ESTIMATED_DOWNTIME_HOURS FLOAT,
    ESTIMATED_OEE_PCT FLOAT
);

CREATE OR REPLACE TABLE PREDICTIVEAI_FORGE.INDUSTRIAL.OEE_SUSTAINABILITY (
    MACHINE_ID VARCHAR,
    FAILURE_RISK_PCT FLOAT,
    AVAILABILITY_PCT FLOAT,
    PERFORMANCE_PCT FLOAT,
    QUALITY_PCT FLOAT,
    OEE_PCT FLOAT,
    ESTIMATED_DOWNTIME_HOURS FLOAT,
    ESTIMATED_ENERGY_WASTE_KWH FLOAT,
    ESTIMATED_MATERIAL_WASTE_KG FLOAT,
    ESTIMATED_CO2_KG FLOAT
);

CREATE OR REPLACE TABLE PREDICTIVEAI_FORGE.INDUSTRIAL.FACTORY_RESILIENCE (
    FACTORY_RESILIENCE_SCORE FLOAT,
    STATUS VARCHAR,
    AVERAGE_MACHINE_RISK_PCT FLOAT,
    HIGH_RISK_MACHINE_RATIO_PCT FLOAT,
    AVERAGE_CASCADE_EXPOSURE_PCT FLOAT,
    AVERAGE_OEE_PCT FLOAT,
    ESTIMATED_DOWNTIME_EXPOSURE_HOURS FLOAT,
    ESTIMATED_ENERGY_WASTE_KWH FLOAT,
    DATA_QUALITY_SCORE FLOAT
);
